"""Parquet files under data/, queried with DuckDB. No database server.

data/sample/  synthetic demo data (committed, regenerated by scripts/make_synthetic.py)
data/live/    real public aggregates written by scripts/collect.py (daily job)
"""

from __future__ import annotations

from pathlib import Path

import duckdb
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"


def path(name: str, mode: str = "sample") -> Path:
    return DATA / mode / f"{name}.parquet"


def write(df: pd.DataFrame, name: str, mode: str = "sample") -> Path:
    p = path(name, mode)
    p.parent.mkdir(parents=True, exist_ok=True)
    df.to_parquet(p, index=False)
    return p


def append(df: pd.DataFrame, name: str, keys: list[str], mode: str = "live") -> Path:
    """Upsert by keys: newer rows replace older ones with the same keys."""
    old = read(name, mode)
    merged = pd.concat([old, df], ignore_index=True) if old is not None else df
    merged = merged.drop_duplicates(subset=keys, keep="last")
    return write(merged, name, mode)


def read(name: str, mode: str = "sample") -> pd.DataFrame | None:
    p = path(name, mode)
    return pd.read_parquet(p) if p.exists() else None


def query(sql: str, mode: str = "sample") -> pd.DataFrame:
    """SQL over the parquet files, e.g. query("select * from posts limit 5")."""
    con = duckdb.connect()
    for p in (DATA / mode).glob("*.parquet"):
        con.execute(f"create view {p.stem} as select * from read_parquet('{p.as_posix()}')")
    return con.execute(sql).df()
